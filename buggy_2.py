import pandas as pd

def load(path):
    df = pd.read_csv(path, encoding="utf-8")
    return df

def summarize(df):
    # 단가 x 수량으로 매출액 컬럼을 만든 뒤 카테고리별 합계를 낸다
    #df["매출액"] = df["단가"] * df["수량"]        # <-- 여기가 문제의 줄
    df["매출액"] = df["price"] * df["quantity"]  # FIXED : 컬럼명을 'price'와 'quantity'로 변경 [컬럼명 불일치 발생하기 때문]
    return df.groupby("category")["매출액"].sum()

